def _lines(s: str) -> list[str]:
    """Формат ноутбука требует перенос в конце каждой строки, кроме последней.

    Без этого строки склеиваются и ячейка не выполняется.
    """
    parts = s.strip("\n").split("\n")
    return [p + "\n" for p in parts[:-1]] + parts[-1:]


